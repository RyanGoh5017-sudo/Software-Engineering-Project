using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using RestuarantOrderSystem.Models;
using System;
using System.Collections.Generic;

namespace RestuarantOrderSystem.Services
{
    public class PdfReportService
    {
        public byte[] GenerateSalesReport(List<Order> orders, DateTime startDate, DateTime endDate)
        {
            return Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Margin(30);
                    page.Header().Column(col =>
                    {
                        col.Item().Text("RROMS Restaurant Management System").Bold().FontSize(22).FontColor(Colors.Blue.Medium);
                        col.Item().Text($"Executive Sales Report ({startDate:yyyy-MM-dd} to {endDate:yyyy-MM-dd})").FontSize(14).Italic();
                        col.Item().PaddingBottom(10).LineHorizontal(1).LineColor(Colors.Grey.Lighten1);
                    });

                    page.Content().PaddingVertical(10).Column(col =>
                    {
                        col.Item().Table(table =>
                        {
                            table.ColumnsDefinition(columns =>
                            {
                                columns.ConstantColumn(60);
                                columns.RelativeColumn();
                                columns.RelativeColumn();
                                columns.ConstantColumn(100);
                            });

                            table.Header(header =>
                            {
                                header.Cell().Text("Order ID").Bold();
                                header.Cell().Text("Date & Time").Bold();
                                header.Cell().Text("Status").Bold();
                                header.Cell().Text("Amount ($)").Bold();
                            });

                            decimal grandTotal = 0;
                            foreach (var order in orders)
                            {
                                table.Cell().Text($"#{order.OrderId}");
                                table.Cell().Text(order.OrderDate.ToString("yyyy-MM-dd HH:mm"));
                                table.Cell().Text(order.Status.ToString());
                                table.Cell().Text($"${order.TotalAmount:F2}");
                                grandTotal += order.TotalAmount;
                            }

                            table.Footer(footer =>
                            {
                                footer.Cell().ColumnSpan(3).AlignRight().Text("Grand Total Revenue:").Bold();
                                footer.Cell().Text($"${grandTotal:F2}").Bold().FontColor(Colors.Green.Darken2);
                            });
                        });
                    });

                    page.Footer().AlignCenter().Text(x =>
                    {
                        x.Span("Generated by RROMS System | Page ");
                        x.CurrentPageNumber();
                    });
                });
            }).GeneratePdf();
        }
    }
}